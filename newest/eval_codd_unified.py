def load_test_cases(dataset, max_cases=32):
    """Load test cases with ground truth labels."""
    cases = []
    if dataset == "Synapse":
        test_dir = f"{ROOT}/data/Synapse_preprocess/test_vol_h5"
        for fname in sorted(os.listdir(test_dir))[:max_cases]:
            path = os.path.join(test_dir, fname)
            if fname.endswith('.h5'):
                import h5py
                with h5py.File(path, 'r') as f:
                    img = f['image'][:].astype(np.float32)
                    lbl = f['label'][:].astype(np.float32)
            else:
                data = np.load(path, allow_pickle=True)
                img = data['image'].astype(np.float32) if isinstance(data, np.ndarray) else data['image'].astype(np.float32)
                lbl = data['label'].astype(np.float32) if isinstance(data, np.ndarray) else np.zeros_like(img)

            case_name = os.path.splitext(fname)[0].replace('.npy', '')
            valid = [s for s in range(img.shape[0]) if (lbl[s] > 0).sum() > 100]
            if not valid:
                valid = list(range(min(img.shape[0], 8)))
            valid = valid[:8]

            for s in valid:
                slc_img = img[s].copy()
                if slc_img.max() > 1.0:
                    slc_img = np.clip(slc_img, -200, 300)
                    slc_img = (slc_img - slc_img.min()) / (slc_img.max() - slc_img.min() + 1e-6) * 255.0
                from scipy.ndimage import zoom
                h_s, w_s = IMAGE_SIZE / slc_img.shape[0], IMAGE_SIZE / slc_img.shape[1]
                slc_img = zoom(slc_img, (h_s, w_s), order=3)
                slc_lbl = zoom(lbl[s], (h_s, w_s), order=0)
                cases.append({"case_name": f"{case_name}_slice{s}", "image": slc_img, "label": slc_lbl, "vol_name": case_name})

    elif dataset == "ISIC":
        from PIL import Image
        test_dir = f"{ROOT}/data/ISIC/ISBI2016_ISIC_Part1_Test_Data"
        gt_dir = f"{ROOT}/data/ISIC/ISBI2016_ISIC_Part1_Test_GroundTruth"
        for fname in sorted(os.listdir(test_dir))[:max_cases]:
            if not fname.endswith('.jpg'):
                continue
            base = os.path.splitext(fname)[0]
            gt_path = os.path.join(gt_dir, f"{base}_Segmentation.png")
            if not os.path.exists(gt_path):
                continue
            img = Image.open(os.path.join(test_dir, fname)).convert('RGB').resize((IMAGE_SIZE, IMAGE_SIZE), Image.BILINEAR)
            gt = Image.open(gt_path).convert('L').resize((IMAGE_SIZE, IMAGE_SIZE), Image.NEAREST)
            img_np = np.array(img).astype(np.float32)
            gt_np = (np.array(gt) > 128).astype(np.float32)
            if gt_np.sum() < 100:
                continue
            cases.append({"case_name": base, "image": img_np, "label": gt_np})

    elif dataset == "REFUGE":
        from PIL import Image
        test_dir = f"{ROOT}/data/REFUGE-Multirater/Test-400"
        subdirs = sorted([d for d in os.listdir(test_dir) if os.path.isdir(os.path.join(test_dir, d))])
        for subdir in subdirs[:max_cases]:
            sp = os.path.join(test_dir, subdir)
            if not os.path.isdir(sp):
                continue
            # Load main image: {case}.jpg (not the _disc.bmp or _cup.bmp)
            case_img = os.path.join(sp, f"{subdir}.jpg")
            if not os.path.exists(case_img):
                # Fallback: find any .jpg that's not _disc or _cup
                jpgs = [f for f in os.listdir(sp) if f.endswith('.jpg') and '_disc' not in f and '_cup' not in f]
                if jpgs:
                    case_img = os.path.join(sp, jpgs[0])
                else:
                    continue
            img = Image.open(case_img).convert('RGB').resize((IMAGE_SIZE, IMAGE_SIZE), Image.BILINEAR)
            img_np = np.array(img).astype(np.float32)

            # Load ground truth: {case}_disc.bmp and {case}_cup.bmp
            # REFUGE BMP format: disc=128(disc)/255(bg), cup=0(cup)/255(bg)
            disc_path = os.path.join(sp, f"{subdir}_disc.bmp")
            cup_path = os.path.join(sp, f"{subdir}_cup.bmp")
            if os.path.exists(disc_path) and os.path.exists(cup_path):
                disc_raw = np.array(Image.open(disc_path).resize((IMAGE_SIZE, IMAGE_SIZE), Image.NEAREST))
                cup_raw = np.array(Image.open(cup_path).resize((IMAGE_SIZE, IMAGE_SIZE), Image.NEAREST))
                disc_gt = (disc_raw == 128).astype(np.float32)  # 128 = disc
                cup_gt = (cup_raw == 0).astype(np.float32)      # 0 = cup
                label = np.stack([disc_gt, cup_gt], axis=0)
            else:
                label = np.zeros((2, IMAGE_SIZE, IMAGE_SIZE), dtype=np.float32)
            cases.append({"case_name": subdir, "image": img_np, "label": label})

    return cases


def load_adv_image(adv_dir, case_name, is_3d=False):
    """Load adversarial image from saved PNG."""
    import matplotlib.image as mpimg

    if is_3d:
        # Synapse: {adv_dir}/{vol_name}/{slice_idx}.png
        vol_name = case_name.split("_slice")[0]
        slice_idx = case_name.split("_slice")[1] if "_slice" in case_name else "0"
        vol_dir = os.path.join(adv_dir, vol_name)
        png_path = os.path.join(vol_dir, f"{slice_idx}.png")
        if not os.path.exists(png_path):
            # Try direct path
            png_path = os.path.join(adv_dir, f"{case_name}.png")
        if not os.path.exists(png_path):
            return None
        adv = mpimg.imread(png_path)
        if adv.ndim == 3 and adv.shape[2] == 3:
            adv = adv[:, :, 0]  # grayscale
        return adv
    else:
        # ISIC/REFUGE: {adv_dir}/{case_name}.png
        png_path = os.path.join(adv_dir, f"{case_name}.png")
        if not os.path.exists(png_path):
            # Try as directory
            case_dir = os.path.join(adv_dir, case_name)
            if os.path.isdir(case_dir):
                pngs = sorted([f for f in os.listdir(case_dir) if f.endswith('.png')])
                if pngs:
                    png_path = os.path.join(case_dir, pngs[0])
        if not os.path.exists(png_path):
            return None
        adv = mpimg.imread(png_path)
        if adv.ndim == 3 and adv.shape[2] == 3:
            pass  # RGB image
        elif adv.ndim == 2:
            adv = np.stack([adv]*3, axis=-1)
        return adv


