# Victim configs
def get_victim_config(vit):
    """Build victim model configs for a given ViT size."""
    configs = {}
    for ds in ["Synapse", "ISIC", "REFUGE"]:
        # SAMed
        samed_link = os.path.join(BEST, f"SAMed_{ds}_{vit}.pth")
        if os.path.exists(samed_link):
            samed_ckpt = os.path.realpath(samed_link)
            ncls = {"Synapse": 8, "ISIC": 1, "REFUGE": 2}[ds]
            configs[f"{ds}_SAMed"] = {"method": "SAMed", "dataset": ds, "ckpt": samed_ckpt, "n_classes": ncls}
        # MSA
        msa_link = os.path.join(BEST, f"MSA_{ds}_{vit}.pth")
        if os.path.exists(msa_link):
            msa_ckpt = os.path.realpath(msa_link)
            mmo = {"Synapse": 9, "ISIC": 1, "REFUGE": 1}[ds]
            configs[f"{ds}_MSA"] = {"method": "MSA", "dataset": ds, "ckpt": msa_ckpt, "n_classes": mmo}
    return configs


