def evaluate_samed_case(net, img_np, label_np, device, dataset, n_classes):
    """Evaluate SAMed on a single image."""
    # Prepare image tensor: ensure [1, 3, H, W] in 0-255 range
    if img_np.ndim == 2:
        img_np = np.stack([img_np] * 3, axis=-1)
    elif img_np.ndim == 3 and img_np.shape[0] == 3:
        img_np = img_np.transpose(1, 2, 0)  # C,H,W -> H,W,C

    # Ensure (H, W, 3)
    if img_np.shape[-1] not in (1, 3):
        img_np = np.stack([img_np[:, :, 0]] * 3, axis=-1)

    # Convert to [0, 255] if needed
    if img_np.max() <= 2.0:
        img_np = img_np * 255.0
    img_np = np.clip(img_np, 0, 255).astype(np.float32)

    # To tensor [1, 3, H, W]
    img_t = torch.from_numpy(img_np.transpose(2, 0, 1)).float().unsqueeze(0).to(device)

    with torch.no_grad():
        net.eval()
        outputs = net(img_t, True, IMAGE_SIZE)
        masks = outputs['masks']

    if dataset == "Synapse":
        pred = torch.argmax(torch.softmax(masks.float(), dim=1), dim=1).squeeze(0).cpu().numpy()
        if torch.is_tensor(label_np):
            label_np = label_np.cpu().numpy()
        dices = []
        for c in range(1, n_classes):
            pc = (pred == c).astype(np.float32)
            tc = (label_np == c).astype(np.float32)
            inter = (pc * tc).sum()
            denom = pc.sum() + tc.sum()
            dices.append(2.0 * inter / (denom + 1e-8) if denom > 0 else 1.0)
        return float(np.mean(dices))

    elif dataset == "ISIC":
        probs = torch.sigmoid(masks).squeeze().cpu().numpy()
        gt = (label_np > 0.5).astype(np.float32)
        if torch.is_tensor(gt):
            gt = gt.cpu().numpy()
        best_d = 0.0
        for th in np.arange(0.1, 1.0, 0.1):
            pb = (probs > th).astype(np.float32)
            if pb.ndim > 1:
                pb = pb.squeeze()
            d = 2.0 * (pb * gt.squeeze()).sum() / (pb.sum() + gt.squeeze().sum() + 1e-8)
            if d > best_d:
                best_d = d
        return float(best_d)

    elif dataset == "REFUGE":
        masks_sm = torch.softmax(masks, dim=1).squeeze(0).cpu().numpy()
        pred = np.argmax(masks_sm, axis=0)
        if torch.is_tensor(label_np):
            label_np = label_np.cpu().numpy()
        disc_gt = (label_np[0] > 0.5).astype(np.float32) if label_np.ndim > 2 else (label_np > 0).astype(np.float32)
        cup_gt = (label_np[1] > 0.5).astype(np.float32) if label_np.ndim > 2 else np.zeros_like(disc_gt)
        disc_p = (pred == 1).astype(np.float32)
        cup_p = (pred == 2).astype(np.float32)
        d_disc = 2.0 * (disc_p * disc_gt).sum() / (disc_p.sum() + disc_gt.sum() + 1e-8)
        d_cup = 2.0 * (cup_p * cup_gt).sum() / (cup_p.sum() + cup_gt.sum() + 1e-8)
        return float((d_disc + d_cup) / 2.0)


def evaluate_msa_case(model, img_np, label_np, device, dataset, n_classes):
    """Evaluate MSA on a single image."""
    from PIL import Image as PILImage
    from torchvision.transforms import Resize, Compose, ToTensor, Lambda

    # Prepare image as HxWxC uint8
    if img_np.ndim == 3 and img_np.shape[0] == 3:
        img_np = img_np.transpose(1, 2, 0)
    if img_np.ndim == 2:
        img_np = np.stack([img_np]*3, axis=-1)
    if img_np.max() <= 2.0:
        img_np = img_np * 255.0
    img_uint8 = np.clip(img_np, 0, 255).astype(np.uint8)

    img_pil = PILImage.fromarray(img_uint8).convert('RGB')
    transform = Compose([Resize((IMAGE_SIZE, IMAGE_SIZE)), ToTensor(), Lambda(lambda x: x * 255)])
    img_t = transform(img_pil).unsqueeze(0).to(device)

    # Ground truth
    if torch.is_tensor(label_np):
        gt = (label_np > 0.5).float().cpu().numpy()
    else:
        gt = (label_np > 0.5).astype(np.float32)

    # Ground truth processing
    if gt.ndim > 2:
        gt_flat = gt[0] if gt.shape[0] < 10 else gt.squeeze()
    else:
        gt_flat = gt.squeeze()

    # Click prompt
    if n_classes > 2:
        # Multi-class (Synapse): one click per class
        pt_list, lbl_list = [], []
        for c in range(1, n_classes):
            class_mask = (gt_flat == c)
            indices = np.argwhere(class_mask)
            if len(indices) > 0:
                r, col = indices[random.randint(0, len(indices) - 1)]
                pt_list.append([float(col), float(r)])
                lbl_list.append(1)
            else:
                pt_list.append([0.0, 0.0])
                lbl_list.append(0)
        pt = torch.tensor([pt_list], dtype=torch.float, device=device)
        pt_label = torch.tensor([lbl_list], dtype=torch.int, device=device)
    else:
        # Binary: single click
        indices = np.argwhere(gt_flat > 0)
        if len(indices) == 0:
            pt = torch.tensor([[[0.0, 0.0]]], device=device)
            pt_label = torch.tensor([[0]], dtype=torch.int, device=device)
        else:
            r, c = indices[random.randint(0, len(indices) - 1)]
            pt = torch.tensor([[[float(c), float(r)]]], device=device)
            pt_label = torch.tensor([[1]], dtype=torch.int, device=device)

    with torch.no_grad():
        model.eval()
        imgs_pre = model.preprocess(img_t)
        image_emb = model.image_encoder(imgs_pre)
        sparse_emb, dense_emb = model.prompt_encoder(points=(pt, pt_label), boxes=None, masks=None)
        pred, _ = model.mask_decoder(
            image_embeddings=image_emb,
            image_pe=model.prompt_encoder.get_dense_pe(),
            sparse_prompt_embeddings=sparse_emb,
            dense_prompt_embeddings=dense_emb,
            multimask_output=(n_classes > 1),
        )
        pred = F.interpolate(pred, size=(IMAGE_SIZE, IMAGE_SIZE), mode="bilinear", align_corners=False)

    if n_classes > 2:
        # Multi-class (Synapse): argmax over class dimension
        pred_classes = torch.argmax(pred, dim=1).squeeze(0).cpu().numpy()
        dices = []
        for c in range(1, n_classes):
            pc = (pred_classes == c).astype(np.float32)
            tc = (gt_flat == c).astype(np.float32)
            inter = (pc * tc).sum()
            denom = pc.sum() + tc.sum()
            dices.append(2.0 * inter / (denom + 1e-8) if denom > 0 else 1.0)
        return float(np.mean(dices))
    else:
        # Binary (ISIC/REFUGE): sigmoid + threshold sweep
        probs = torch.sigmoid(pred).squeeze().cpu().numpy()
        if probs.ndim > 1:
            probs = probs.squeeze()
        best_d = 0.0
        for th in np.arange(0.1, 1.0, 0.1):
            pb = (probs > th).astype(np.float32)
            if pb.shape != gt_flat.shape:
                pb = pb.reshape(gt_flat.shape)
            d = 2.0 * (pb * gt_flat).sum() / (pb.sum() + gt_flat.sum() + 1e-8)
            if d > best_d:
                best_d = d
        return float(best_d)


