def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--vit", type=str, default="vit_b", choices=["vit_b", "vit_l", "vit_h"])
    parser.add_argument("--gpu", type=int, default=0)
    parser.add_argument("--mode", type=str, default="radial",
                       choices=["radial", "tangential", "isotropic", "misaligned", "random_noise", "clean"])
    parser.add_argument("--srs", action="store_true")
    parser.add_argument("--max_cases", type=int, default=16)
    parser.add_argument("--dataset_only", type=str, default="", help="Only evaluate this dataset")
    parser.add_argument("--victim_only", type=str, default="", help="Only evaluate this victim type (SAMed/MSA)")
    args = parser.parse_args()

    device = torch.device(f"cuda:{args.gpu}")
    print(f"CODD Unified Evaluation — {args.vit} mode={args.mode} SRS={args.srs}")
    print(f"GPU: cuda:{args.gpu}")

    # Build victim list
    victim_configs = get_victim_config(args.vit)
    if args.dataset_only:
        victim_configs = {k: v for k, v in victim_configs.items() if args.dataset_only in k}
    if args.victim_only:
        victim_configs = {k: v for k, v in victim_configs.items() if args.victim_only in k}

    print(f"Victims: {list(victim_configs.keys())}")

    # Load test cases per dataset
    datasets_needed = set(v["dataset"] for v in victim_configs.values())
    test_data = {}
    for ds in datasets_needed:
        cases = load_test_cases(ds, args.max_cases)
        test_data[ds] = cases
        print(f"  {ds}: {len(cases)} test cases")

    # Load victim models
    victims = {}
    for vname, vcfg in victim_configs.items():
        print(f"Loading {vname}...")
        try:
            if vcfg["method"] == "SAMed":
                model = load_samed_model(args.vit, SAM_CKPT[args.vit], vcfg["ckpt"],
                                        IMAGE_SIZE, vcfg["n_classes"], device=device)
            else:
                model = load_medsa_model(args.vit, SAM_CKPT[args.vit], vcfg["ckpt"],
                                        IMAGE_SIZE, vcfg["n_classes"], device=device)
            victims[vname] = (model, vcfg)
        except Exception as e:
            print(f"  ERROR loading {vname}: {e}")

    # Determine adv directory
    srs_tag = "_srs" if args.srs else ""
    adv_dir = os.path.join(ATTACK_BASE, f"{args.vit}_{{ds}}_{args.mode}{srs_tag}")

    # Evaluate
    all_results = {}

    for ds_name, ds_cases in test_data.items():
        ds_victims = {vn: v for vn, v in victims.items() if ds_name in vn}
        if not ds_victims:
            continue

        # Resolve adv dir for this dataset
        this_adv_dir = adv_dir.format(ds=ds_name)
        has_adv = os.path.isdir(this_adv_dir) and args.mode != "clean"

        print(f"\n{'='*50}")
        print(f"Dataset: {ds_name} | Cases: {len(ds_cases)} | Victims: {list(ds_victims.keys())}")
        print(f"Adv dir: {this_adv_dir} | Has adv: {has_adv}")

        for vname, (vmodel, vcfg) in ds_victims.items():
            print(f"\n  Evaluating {vname}...")
            clean_dices = []
            adv_dices = []

            for case in ds_cases:
                case_name = case["case_name"]
                img_np = case["image"]
                lbl_np = case["label"]

                try:
                    # Clean evaluation
                    if vcfg["method"] == "SAMed":
                        clean_d = evaluate_samed_case(vmodel, img_np, lbl_np, device, ds_name, vcfg["n_classes"])
                    else:
                        clean_d = evaluate_msa_case(vmodel, img_np, lbl_np, device, ds_name, vcfg["n_classes"])
                    clean_dices.append(clean_d)

                    # Adversarial evaluation
                    if has_adv:
                        is_3d = (ds_name == "Synapse")
                        adv_np = load_adv_image(this_adv_dir, case_name, is_3d=is_3d)
                        if adv_np is not None:
                            if vcfg["method"] == "SAMed":
                                adv_d = evaluate_samed_case(vmodel, adv_np, lbl_np, device, ds_name, vcfg["n_classes"])
                            else:
                                adv_d = evaluate_msa_case(vmodel, adv_np, lbl_np, device, ds_name, vcfg["n_classes"])
                            adv_dices.append(adv_d)
                        else:
                            adv_dices.append(clean_d)  # fallback to clean if no adv image
                    else:
                        adv_dices.append(clean_d)
                except Exception as e:
                    print(f"    ERROR {case_name}: {e}")
                    continue

            # Aggregate
            mean_clean = float(np.mean(clean_dices)) if clean_dices else float("nan")
            mean_adv = float(np.mean(adv_dices)) if adv_dices else float("nan")
            mean_drop = mean_clean - mean_adv

            all_results[f"{ds_name}_{vname}"] = {
                "dataset": ds_name,
                "victim": vname,
                "method": vcfg["method"],
                "vit": args.vit,
                "n_cases": len(clean_dices),
                "mean_clean_dice": mean_clean,
                "mean_adv_dice": mean_adv,
                "mean_dice_drop": mean_drop,
                "clean_dices_per_case": clean_dices,
                "adv_dices_per_case": adv_dices,
            }
            print(f"    Clean Dice: {mean_clean:.4f} | Adv Dice: {mean_adv:.4f} | Drop: {mean_drop:.4f}")

        # Cleanup victim models after each dataset
        for vname in list(ds_victims.keys()):
            if vname not in victims:
                continue

    # Save results
    result_file = os.path.join(OUTPUT_DIR, f"eval_{args.vit}_{args.mode}{srs_tag}.json")
    with open(result_file, 'w') as f:
        json.dump(all_results, f, indent=2)
    print(f"\nResults saved to {result_file}")

    # Cleanup
    for vmodel, _ in victims.values():
        del vmodel
    gc.collect()
    torch.cuda.empty_cache()

    # Print summary table
    print(f"\n{'='*70}")
    print(f"SUMMARY: {args.vit} mode={args.mode}")
    print(f"{'Victim':<30} {'Clean':>8} {'Adv':>8} {'Drop':>8}")
    print("-" * 55)
    for key in sorted(all_results.keys()):
        r = all_results[key]
        print(f"{key:<30} {r['mean_clean_dice']:>8.4f} {r['mean_adv_dice']:>8.4f} {r['mean_dice_drop']:>8.4f}")

    # Track average drops
    drops = [r["mean_dice_drop"] for r in all_results.values() if not np.isnan(r["mean_dice_drop"])]
    if drops:
        print(f"\nMean Drop: {np.mean(drops):.4f} ± {np.std(drops):.4f} ({len(drops)} models)")
        print(f"Positive drops (attack works): {sum(1 for d in drops if d > 0.005)}/{len(drops)}")


if __name__ == "__main__":
    main()
