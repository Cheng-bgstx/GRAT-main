import h5py
import os
import numpy as np
from PIL import Image
from tqdm import tqdm
import argparse

def png_to_h5_synapse(adv_png_dir, original_h5_dir, output_h5_dir, list_dir):
    """
    Repackages PNG slices generated by Sam_attack.py into .npy.h5 files
    readable by val.py.
    """
    if not os.path.exists(output_h5_dir):
        os.makedirs(output_h5_dir)

    # Read the test list
    test_list_path = os.path.join(list_dir, 'test_vol.txt')
    with open(test_list_path, 'r') as f:
        test_list = [i.strip() for i in f.readlines()]

    print(f"Starting conversion: {len(test_list)} cases total")
    print(f"PNG Source Dir: {adv_png_dir}")
    print(f"Original H5 Dir (for Labels): {original_h5_dir}")
    print(f"Output Dir: {output_h5_dir}")

    for case_name in tqdm(test_list):
        # 1. Load original H5 file (to retrieve the ground truth Label)
        orig_file_path = os.path.join(original_h5_dir, f"{case_name}.npy.h5")
        if not os.path.exists(orig_file_path):
            print(f"Skipping: Original file not found {orig_file_path}")
            continue
            
        h5f_orig = h5py.File(orig_file_path, 'r')
        label = h5f_orig['label'][:]  # Shape: (Slice, H, W) or (H, W, Slice)
        original_image = h5f_orig['image'][:] # Used for shape checking
        h5f_orig.close()

        # 2. Read adversarial PNG slices
        case_png_dir = os.path.join(adv_png_dir, case_name)
        if not os.path.exists(case_png_dir):
            print(f"Skipping: PNG directory not found {case_png_dir}")
            continue

        # Synapse data is typically stored as (Slice, H, W). 
        # We need to read images in order of their slice index.
        num_slices = label.shape[0] 
        
        adv_vol = []
        for i in range(num_slices):
            img_path = os.path.join(case_png_dir, f"{i}.png")
            if not os.path.exists(img_path):
                print(f"Warning: {case_name} missing slice {i}.png, using zero placeholder.")
                img_slice = np.zeros((512, 512)) 
            else:
                # Match the original Synapse H5 contract: float32 in [0, 1].
                img = Image.open(img_path).convert('L')
                img_slice = np.array(img, dtype=np.float32) / 255.0

            adv_vol.append(img_slice)
        
        adv_vol = np.array(adv_vol) # Shape: (Slice, H, W)
        if not (0.0 <= float(adv_vol.min()) and float(adv_vol.max()) <= 1.0):
            raise ValueError(f"{case_name}: adversarial volume violates [0,1] input scale")

        # 3. Save as new H5 file
        output_filepath = os.path.join(output_h5_dir, f"{case_name}.npy.h5")
        f = h5py.File(output_filepath, 'w')
        
        # Verify shape consistency
        if adv_vol.shape != original_image.shape:
             # If dimensions are transposed in original file, you might need to transpose adv_vol here.
             pass
             
        f.create_dataset('image', data=adv_vol)
        f.create_dataset('label', data=label)
        f.close()

if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument('--adv_path', type=str, required=True, help='Root directory of PNGs output by Sam_attack.py')
    parser.add_argument('--orig_path', type=str, required=True, help='Original Synapse test_vol_h5 directory')
    parser.add_argument('--out_h5_path', type=str, required=True, help='Directory to save the converted H5 files')
    parser.add_argument('--list_dir', type=str, default='./lists/lists_Synapse/', help='Directory containing test_vol.txt')
    
    args = parser.parse_args()
    
    png_to_h5_synapse(args.adv_path, args.orig_path, args.out_h5_path, args.list_dir)
